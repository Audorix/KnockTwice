// Generates docs/third-party-licenses.md from the restored packages (no network access):
// NuGet packages in the API's dependency closure (obj/project.assets.json + .nuspec files in the
// local package cache) and npm packages shipped with the web app (package-lock.json, dev excluded).
//
//   dotnet restore && (cd web && npm ci) && node scripts/third-party-licenses.mjs
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { homedir } from 'node:os';
import { join } from 'node:path';

const root = new URL('..', import.meta.url).pathname.replace(/^\/(\w:)/, '$1');
const assets = JSON.parse(readFileSync(join(root, 'src/Api/Audorix.KnockTwice.Api/obj/project.assets.json'), 'utf8'));
const packagesRoot = assets.project?.restore?.packagesPath ?? join(homedir(), '.nuget', 'packages');

function nugetLicense(id, version) {
  const nuspec = join(packagesRoot, id.toLowerCase(), version.toLowerCase(), `${id.toLowerCase()}.nuspec`);
  if (!existsSync(nuspec)) return 'unknown (package not in cache)';
  const xml = readFileSync(nuspec, 'utf8');
  const expression = /<license\s+type="expression"\s*>([^<]+)<\/license>/i.exec(xml)?.[1];
  if (expression) return expression.trim();
  const file = /<license\s+type="file"\s*>([^<]+)<\/license>/i.exec(xml)?.[1];
  if (file) return `see ${file.trim()} in the package`;
  const url = /<licenseUrl>([^<]+)<\/licenseUrl>/i.exec(xml)?.[1]?.trim();
  if (url?.includes('aka.ms/deprecateLicenseUrl')) return 'see package';
  return url ? `see ${url}` : 'unknown';
}

const nuget = Object.entries(assets.libraries)
  .filter(([, lib]) => lib.type === 'package')
  .map(([key]) => {
    const [id, version] = key.split('/');
    return { id, version, license: nugetLicense(id, version) };
  })
  .sort((a, b) => a.id.localeCompare(b.id));

// The runtime closure of the web app: walk from its "dependencies" through the lockfile, resolving
// each name the way Node does (nearest node_modules first). Build tools are never reached.
const lock = JSON.parse(readFileSync(join(root, 'web/package-lock.json'), 'utf8'));
const app = 'apps/chat-web';
const parentOf = (dir) =>
  dir.includes('/node_modules/') ? dir.slice(0, dir.lastIndexOf('/node_modules/')) : dir === '' ? null : '';
const resolve = (from, name) => {
  for (let dir = from; dir !== null; dir = parentOf(dir)) {
    const path = `${dir ? `${dir}/` : ''}node_modules/${name}`;
    if (lock.packages[path]) return path;
  }
  return null;
};
const seen = new Map();
const visit = (from, name) => {
  const path = resolve(from, name);
  if (!path || seen.has(path)) return;
  const pkg = lock.packages[path];
  seen.set(path, pkg);
  for (const dep of Object.keys({ ...pkg.dependencies, ...pkg.optionalDependencies })) visit(path, dep);
};
for (const dep of Object.keys(lock.packages[app].dependencies ?? {})) visit(app, dep);
const npm = [...seen.entries()]
  .map(([path, pkg]) => ({ id: path.slice(path.lastIndexOf('node_modules/') + 'node_modules/'.length), version: pkg.version, license: pkg.license ?? 'unknown' }))
  .filter((p, i, all) => all.findIndex((q) => q.id === p.id && q.version === p.version) === i)
  .sort((a, b) => a.id.localeCompare(b.id));

const summary = (list) => Object.entries(list.reduce((acc, p) => ((acc[p.license] = (acc[p.license] ?? 0) + 1), acc), {}))
  .sort((a, b) => b[1] - a[1]).map(([license, count]) => `${license} (${count})`).join(', ');
const table = (list) => ['| Package | Version | License |', '| --- | --- | --- |', ...list.map((p) => `| ${p.id} | ${p.version} | ${p.license} |`)].join('\n');

const markdown = `# Third-party licenses

Generated by \`node scripts/third-party-licenses.mjs\` from the restored packages. Regenerate it
whenever dependencies change. Knock Twice itself is MIT-licensed (see \`LICENSE\`).

Review result for this release: every package that ships is under a permissive license (MIT,
Apache-2.0, BSD or similar) compatible with distributing Knock Twice under MIT. Entries marked
"see …" point at the license text inside the package. Build and test tools (SDKs, test frameworks,
TypeScript, Vite, Vitest and other npm \`devDependencies\`) are not shipped and are not listed.

Runtimes and base images used but not redistributed by this repository: .NET (MIT), Node.js (MIT,
build only), nginx (BSD-2-Clause), PostgreSQL (PostgreSQL License), Docker images from
\`mcr.microsoft.com\`, \`node\`, \`nginxinc/nginx-unprivileged\`, \`postgres\` and \`axllent/mailpit\`
(development only) under their own licenses.

## .NET packages in the API (${nuget.length})

Licenses: ${summary(nuget)}.

${table(nuget)}

## npm packages in the web app and website chat (${npm.length})

Licenses: ${summary(npm)}.

${table(npm)}
`;

writeFileSync(join(root, 'docs/third-party-licenses.md'), markdown);
console.log(`NuGet: ${nuget.length} (${summary(nuget)})`);
console.log(`npm: ${npm.length} (${summary(npm)})`);
