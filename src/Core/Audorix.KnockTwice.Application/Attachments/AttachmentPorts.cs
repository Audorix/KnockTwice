using Audorix.KnockTwice.Domain.Attachments;

namespace Audorix.KnockTwice.Application.Attachments;

/// <summary>
/// Attachment policy (owner decisions of 2026-11-22) bound from the <c>Attachments</c> section.
/// Limits are per file, per message and per owner (0 disables the quota).
/// </summary>
public sealed class AttachmentSettings
{
    public const string SectionName = "Attachments";

    public static readonly string[] DefaultExtensions = ["jpg", "jpeg", "png", "gif", "webp", "pdf", "docx", "xlsx", "pptx", "txt", "csv", "zip"];

    /// <summary>Feature switch (Phase 9): when off, no new files can be uploaded; existing files stay readable.</summary>
    public bool Enabled { get; set; } = true;

    public long MaxFileSize { get; set; } = 25L * 1024 * 1024;

    public int MaxPerMessage { get; set; } = 10;

    /// <summary>Total size of a person's stored attachments; 0 = unlimited.</summary>
    public long UserQuota { get; set; } = 1024L * 1024 * 1024;

    /// <summary>Allowed extensions (lower case, without dot), a subset of <see cref="FileTypes.Known"/>. Empty = the defaults.</summary>
    public List<string> AllowedExtensions { get; set; } = [];

    /// <summary>Uploads never sent with a message are removed after this long.</summary>
    public TimeSpan AbandonedAfter { get; set; } = TimeSpan.FromHours(24);

    /// <summary>An upload whose bytes never finished arriving is cleaned up after this long.</summary>
    public TimeSpan PendingTimeout { get; set; } = TimeSpan.FromHours(1);

    /// <summary>How often the cleanup job runs (abandoned uploads, content removal retries, rescans).</summary>
    public TimeSpan CleanupInterval { get; set; } = TimeSpan.FromMinutes(1);

    public IReadOnlyCollection<string> EffectiveExtensions =>
        AllowedExtensions.Count == 0 ? DefaultExtensions : AllowedExtensions.Select(e => e.Trim().TrimStart('.').ToLowerInvariant()).ToHashSet(StringComparer.Ordinal);

    public IReadOnlyList<string> Validate()
    {
        var errors = new List<string>();
        if (MaxFileSize is < 1024 or > 5L * 1024 * 1024 * 1024)
        {
            errors.Add("Attachments:MaxFileSize must be between 1 KB and 5 GB.");
        }

        if (MaxPerMessage is < 1 or > 50)
        {
            errors.Add("Attachments:MaxPerMessage must be between 1 and 50.");
        }

        if (UserQuota < 0)
        {
            errors.Add("Attachments:UserQuota must be 0 (unlimited) or positive.");
        }

        var unknown = EffectiveExtensions.Where(e => !FileTypes.Known.ContainsKey(e)).ToList();
        if (unknown.Count > 0)
        {
            errors.Add($"Attachments:AllowedExtensions contains unsupported types: {string.Join(", ", unknown)}. Supported: {string.Join(", ", FileTypes.Known.Keys)}.");
        }

        if (AbandonedAfter < TimeSpan.FromMinutes(1) || PendingTimeout < TimeSpan.FromMinutes(1) || CleanupInterval < TimeSpan.FromSeconds(1))
        {
            errors.Add("Attachments:AbandonedAfter and PendingTimeout must be at least 1 minute, CleanupInterval at least 1 second.");
        }

        return errors;
    }
}

/// <summary>
/// File content storage (ADR-007). Keys are generated by ChatX (<see cref="AttachmentService.NewStorageKey"/>);
/// implementations must still refuse keys that could escape their root. Implementations: local
/// filesystem and S3-compatible object storage.
/// </summary>
public interface IAttachmentStorage
{
    /// <summary>Name for diagnostics (<c>Local</c>, <c>S3</c>).</summary>
    string Name { get; }

    Task PutAsync(string key, Stream content, long length, string contentType, CancellationToken cancellationToken);

    /// <summary>The stored bytes, or null when the object does not exist.</summary>
    Task<Stream?> OpenReadAsync(string key, CancellationToken cancellationToken);

    /// <summary>Idempotent: deleting a missing object succeeds.</summary>
    Task DeleteAsync(string key, CancellationToken cancellationToken);
}

/// <summary>Failure of the storage provider (unreachable, refused). Mapped to 503.</summary>
public sealed class StorageUnavailableException(string message, Exception? inner = null) : Exception(message, inner);

public enum ScanVerdict
{
    Clean = 1,
    Infected = 2,

    /// <summary>The scanner could not give an answer; the file stays quarantined.</summary>
    Unavailable = 3,
}

/// <summary>Malware scanning integration (Architecture §9). Disabled by default (owner decision).</summary>
public interface IMalwareScanner
{
    bool Enabled { get; }

    Task<ScanVerdict> ScanAsync(Stream content, CancellationToken cancellationToken);
}

/// <summary>Scanning switched off: <see cref="Enabled"/> is false and nothing is scanned.</summary>
public sealed class DisabledMalwareScanner : IMalwareScanner
{
    public bool Enabled => false;

    public Task<ScanVerdict> ScanAsync(Stream content, CancellationToken cancellationToken) => Task.FromResult(ScanVerdict.Clean);
}

/// <summary>Attachment metadata persistence. Shares the unit of work with <see cref="Conversations.IConversationStore"/>.</summary>
public interface IAttachmentStore
{
    void Add(Attachment attachment);

    Task<Attachment?> FindAsync(Guid attachmentId, CancellationToken cancellationToken);

    Task<IReadOnlyList<Attachment>> FindManyAsync(IReadOnlyCollection<Guid> attachmentIds, CancellationToken cancellationToken);

    /// <summary>Ready attachments linked to the given messages (read only).</summary>
    Task<IReadOnlyList<Attachment>> ListReadyForMessagesAsync(IReadOnlyCollection<Guid> messageEntryIds, CancellationToken cancellationToken);

    /// <summary>Every attachment linked to the message (tracked, for deletion).</summary>
    Task<IReadOnlyList<Attachment>> ListForMessageAsync(Guid messageEntryId, CancellationToken cancellationToken);

    /// <summary>Total size of the owner's attachments that still hold storage.</summary>
    Task<long> SumStoredSizeAsync(Guid ownerUserId, CancellationToken cancellationToken);

    /// <summary>Unlinked uploads created before <paramref name="readyBefore"/>, and unfinished ones created before <paramref name="pendingBefore"/>.</summary>
    Task<IReadOnlyList<Attachment>> ListAbandonedAsync(DateTimeOffset readyBefore, DateTimeOffset pendingBefore, int limit, CancellationToken cancellationToken);

    /// <summary>Deleted or rejected attachments whose content still has to be removed.</summary>
    Task<IReadOnlyList<Attachment>> ListContentToRemoveAsync(int limit, CancellationToken cancellationToken);

    Task<IReadOnlyList<Attachment>> ListQuarantinedAsync(int limit, CancellationToken cancellationToken);

    Task SaveChangesAsync(CancellationToken cancellationToken);
}
